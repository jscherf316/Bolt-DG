  resource_browser:onmessage(function (msg)
    -- Verts slider: set the unknown-queue vertexcount window.
    local vlo, vhi = msg:match("^vrange:(%d+),(%d+)$")
    if vlo then queue_vmin, queue_vmax = tonumber(vlo), tonumber(vhi); return end
    -- SHOW LARGE toggle: lift the >5000-vert / bbox / upper-bound rejects.
    local sl = msg:match("^show_large:(%d)$")
    if sl then show_large = (sl == "1"); return end
    -- Preview request: modal opened for queue entry #i (1-based).
    local pi = msg:match("^preview:(%d+)$")
    if pi then
      local idx = tonumber(pi)
      local e = last_dumped_list[idx]
      if e and resource_browser then
        -- Payload mirrors the icon path so the panel's triangle rasteriser can
        -- be reused:  "pts:<idx>|<sw>|<sh>|<mvp16>:<pts>"
        -- Resources don't have a real screen box, so pass a canonical 128x128
        -- viewport — MVP is scale-invariant, that just controls output res.
        resource_browser:sendmessage(string.format("pts:%d|128|128|%s:%s",
          idx, e.mvp or "", e.pts or ""))
      end
      return
    end
    -- Match preview: request full mesh data for a row in the Matches tab.
    local pmi = msg:match("^preview_match:(%d+)$")
    if pmi then
      local idx = tonumber(pmi)
      local m = last_dumped_matches_list[idx]
      local d = m and resources_matched_seen[m.key]
      if d and resource_browser then
        resource_browser:sendmessage(string.format(
          "mpts:%d|128|128|%s:%s", idx, d.mvp or "", d.pts or ""))
      end
      return
    end
    if msg == "freeze_queue" then queue_frozen = true; return end
    if msg == "unfreeze_queue" then queue_frozen = false; return end
    -- Mark-for-review: persist the previewed entry's full capture.
    local rq = msg:match("^review_queue:(%d+)$")
    if rq then
      local e = last_dumped_list[tonumber(rq)]
      if e then
        save_review("queue", "?", e.n, e.wx, e.wy or 0, e.wz,
          e.tx, e.tz, e.key, e.pts, e.mvp)
      end
      return
    end
    local rm = msg:match("^review_match:(%d+)$")
    if rm then
      local m = last_dumped_matches_list[tonumber(rm)]
      local d = m and resources_matched_seen[m.key]
      if m and d then
        save_review("match", string.format("%s:t%d", m.name, m.tier or 0),
          d.n or 0, m.wx, 0, m.wz, m.tx, m.tz, m.key, d.pts, d.mvp)
      end
      return
    end
    if msg == "ignore_all" then
      local prior = SET.load_or_seed("resource_ignored.txt") or ""
      if #prior > 0 and not prior:match("\n$") then prior = prior .. "\n" end
      local added = {}
      for k, _ in pairs(resources_learned) do added[#added + 1] = k end
      if #added > 0 then
        bolt.saveconfig("resource_ignored.txt",
          prior .. table.concat(added, "\n") .. "\n")
        last_ign_res_raw = nil
        resources_learned = {}
      end
    end
  end)
end
close_resource_browser = function ()
  if not resource_browser then return end
  resource_browser:close(); resource_browser = nil
end

-- Snapshot dump — called from onswapbuffers. Sorted by ascending distance so
-- the CLOSEST unknown to the player is always index 1. Also pushes a JSON
-- snapshot to the resource panel so the browser can render a live list.
-- last_dumped_list is forward-declared at the top of the file so the resource
-- browser's onmessage handler can see it. Overwritten below on each dump.
local function dump_resource_queue()
  -- FROZEN: list ordering, resource_queue.txt and the panel's rows all stay
  -- exactly as last dumped; only the Matches tab keeps flowing.
  if not queue_frozen then
    local list = {}
    for _, e in pairs(resources_learned) do list[#list + 1] = e end
    table.sort(list, function (a, b) return a.dist2 < b.dist2 end)
    last_dumped_list = list
    local out = {}
    for _, e in ipairs(list) do
      out[#out + 1] = string.format("%s|%d|%d|%d|%d",
        e.key, e.n, e.wx, e.wy, e.wz)
    end
    SET.dev_save("resource_queue.txt", table.concat(out, "\n") .. "\n")
  end

  if resource_browser then
    if not queue_frozen then
    local json = { "[" }
    for i, e in ipairs(last_dumped_list) do
      if i > 40 then break end
      if i > 1 then json[#json + 1] = "," end
      -- The key is n|idx,x,y,z,r,g,b|... — parse out the 5 sample verts.
      local samples = {}
      local first = true
      for chunk in e.key:gmatch("[^|]+") do
        if first then first = false else
          local ix, x, y, z, r, g, bl = chunk:match(
            "^(%-?%d+),(%-?%d+),(%-?%d+),(%-?%d+),(%-?%d+),(%-?%d+),(%-?%d+)$")
          if ix then
            samples[#samples + 1] = string.format(
              "{\"x\":%s,\"y\":%s,\"z\":%s,\"r\":%s,\"g\":%s,\"b\":%s}",
              x, y, z, r, g, bl)
          end
        end
      end
      json[#json + 1] = string.format(
        "{\"n\":%d,\"wx\":%d,\"wy\":%d,\"wz\":%d,\"tx\":%d,\"tz\":%d,\"v\":[%s]}",
        e.n, e.wx, e.wy, e.wz, e.tx, e.tz, table.concat(samples, ","))
    end
    json[#json + 1] = "]"
    local res_msg = "res:" .. table.concat(json)
    if res_msg ~= _res_msg_last then
      _res_msg_last = res_msg
      resource_browser:sendmessage(res_msg)
    end
    end   -- not queue_frozen

    -- Ship the Matches tab payload: everything the classifier hit since the
    -- last dump, with position and match score. Sort by score ascending so
    -- lowest-confidence (highest-score) matches float to the top of the list.
    local mlist = {}
    for _, m in pairs(current_matches) do mlist[#mlist + 1] = m end
    table.sort(mlist, function (a, b)
      if a.score ~= b.score then return a.score > b.score end   -- weakest first
      if a.dist2 ~= b.dist2 then return a.dist2 < b.dist2 end
      return a.name < b.name
    end)
    last_dumped_matches_list = mlist
    local mjson = { "[" }
    for i, m in ipairs(mlist) do
      if i > 80 then break end
      if i > 1 then mjson[#mjson + 1] = "," end
      -- score can be math.huge for exact-key hits that skipped the scorer? no —
      -- we init to math.huge but only push a match when classified is non-nil,
      -- and either 0 (exact) or a finite scorer result is set. Still guard.
      local score_s = (m.score == math.huge) and "-1" or tostring(math.floor(m.score + 0.5))
      local has_pts = resources_matched_seen[m.key] and (resources_matched_seen[m.key].pts or "") ~= ""
      mjson[#mjson + 1] = string.format(
        "{\"name\":\"%s\",\"tier\":%d,\"tx\":%d,\"tz\":%d,\"score\":%s,\"live\":%s}",
        m.name, m.tier, m.tx, m.tz, score_s, has_pts and "true" or "false")
    end
    mjson[#mjson + 1] = "]"
    local matches_msg = "matches:" .. table.concat(mjson)
    if matches_msg ~= _matches_msg_last then
      _matches_msg_last = matches_msg
      resource_browser:sendmessage(matches_msg)
    end
    -- NOT wiped here: current_matches is now a sticky, TTL-aged list (see
    -- record_match / tick_resources) so the Matches tab holds steady between
    -- the ~5Hz scans instead of flickering. Old code reset it every dump.
  end
end

-- Age out stale entries.
local function tick_resources()
  local dead = {}
  for k, e in pairs(resources_learned) do
    e.ttl = e.ttl - 1
    if e.ttl <= 0 then dead[#dead + 1] = k end
  end
  for _, k in ipairs(dead) do resources_learned[k] = nil end
  -- Matches age the same way (sticky list; see record_match).
  local mdead = {}
  for k, m in pairs(current_matches) do
    m.ttl = (m.ttl or 0) - 1
    if m.ttl <= 0 then mdead[#mdead + 1] = k end
  end
  for _, k in ipairs(mdead) do current_matches[k] = nil end
end

