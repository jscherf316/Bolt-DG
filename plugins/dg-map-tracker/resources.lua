-- DINOS (overhaul phase 5). All tiers are one animated mesh at ~3012 verts --
-- pose-varying, so exact-pose prints have near-zero recall -- and tier is
-- carried ONLY by body colour. Detection is the vertex count (clean gate:
-- nothing non-dino is within +-6 of 3012). Tier is nearest-labelled-body-
-- colour, ADVISORY ONLY: it labels + highlights but NEVER binds parity,
-- because the bonus/no-inf colour margin is tight (~26 L1 at T7/T9, and T8
-- is unseen) -- too close to survive lighting for a binding decision. The
-- reference table (data/dino_colors.txt, median vertex RGB per tier from
-- labelled captures) is regenerated by tools/dino-colors.py; NO colour is
-- ever named in code -- classification is pure distance to your prints.
local DINO_N, DINO_NW = 3012, 6
local DINO_ADVISORY_MAX = 55   -- nearest-ref L1 beyond this -> tier unknown
local dino_refs = {}           -- tier -> {r, g, b}
do
  local raw = SET.load_or_seed("dino_colors.txt") or ""
  for line in raw:gmatch("[^\r\n]+") do
    local t, r, g, b = line:match("^%s*(%d+)%s*|%s*(%d+),(%d+),(%d+)")
    if t then dino_refs[tonumber(t)] = { tonumber(r), tonumber(g), tonumber(b) } end
  end
end

-- Median vertex colour over a 32-vert spread, matched to the nearest tier
-- reference. Returns (tier, dist) or nil; tier is nil when the match is
-- beyond DINO_ADVISORY_MAX (an un-referenced tier -- T5/T6/T8 today).
local function dino_tier(event, n)
  if next(dino_refs) == nil then return nil end
  local K, rs, gs, bs = 32, {}, {}, {}
  for i = 1, K do
    local idx = math.max(1, math.min(n, math.floor(i * n / (K + 1))))
    local ok, r, g, b = pcall(event.vertexcolour, event, idx)
    if ok and r then
      rs[#rs + 1] = math.floor(r * 255 + 0.5)
      gs[#gs + 1] = math.floor(g * 255 + 0.5)
      bs[#bs + 1] = math.floor(b * 255 + 0.5)
    end
  end
  if #rs < 8 then return nil end
  table.sort(rs); table.sort(gs); table.sort(bs)
  local m = math.floor(#rs / 2) + 1
  local cr, cg, cb = rs[m], gs[m], bs[m]
  local best, bd = nil, math.huge
  for tier, ref in pairs(dino_refs) do
    local d = math.abs(cr - ref[1]) + math.abs(cg - ref[2]) + math.abs(cb - ref[3])
    if d < bd then bd, best = d, tier end
  end
  if bd > DINO_ADVISORY_MAX then return nil end
  return best, bd
end

