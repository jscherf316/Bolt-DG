  if raw == last_ign_res_raw then return end
  last_ign_res_raw = raw
  resources_ignored = {}
  if raw then
    for line in raw:gmatch("[^\r\n]+") do
      if not line:match("^%s*#") and not line:match("^%s*$") then
        resources_ignored[line] = true
      end
    end
  end
end
reload_resources()
reload_ignored_resources()

-- ---- Guardian doors ---------------------------------------------------------
-- 3D-mesh prints kept SEPARATE from resources (guardian_doors.txt). One print
-- per floor type, so a live guardian matches exactly one, strictly. Matched by
-- the same 5-vert local fingerprint used for keys (position-invariant).
local guardian_by_n = {}   -- n -> { {name, verts_sorted}, ... }
local function reload_guardians()
  local raw = SET.load_or_seed("guardian_doors.txt")
  guardian_by_n = {}
  if raw then
    for line in raw:gmatch("[^\r\n]+") do
      if not line:match("^%s*#") and not line:match("^%s*$") then
        local name, _tier, rest = line:match("^%s*([%w_]+)|(%d+)|(.+)$")
        if name and rest then
          local n, verts = parse_catalog_verts(rest)
          if n and verts and #verts >= 5 then
            local vs = { verts[1], verts[2], verts[3], verts[4], verts[5] }
            table.sort(vs, function (a, b) return a.y < b.y end)
            guardian_by_n[n] = guardian_by_n[n] or {}
            table.insert(guardian_by_n[n], { name = name, verts = vs })
          end
        end
      end
    end
  end
end
reload_guardians()

-- True if a mesh's vertexcount could be a guardian (cheap gate before sampling).
RES.guardian_n = function (n) return guardian_by_n[n] ~= nil end
-- Strict fingerprint match: returns the guardian name (e.g. GUARDIAN_DOOR_3) or
-- nil. Same metric as the ground-key matcher (pos L1 + summed colour), tight
-- cutoff -- a real guardian re-sight scores ~0 against its own floor's print.
RES.guardian_hit = function (event, n)
  local bucket = guardian_by_n[n]
  if not bucket then return nil end
  local step = math.max(1, math.floor(n / 6))
  local live = {}
  for i = 1, 5 do
    local idx = math.min(n, i * step)
    local ok_p, p = pcall(event.vertexpoint, event, idx)
    if not ok_p or not p then return nil end
    local x, y, z = p:get()
    local ok_c, r, g, b = pcall(event.vertexcolour, event, idx)
    if not ok_c then return nil end
    live[i] = {
      x = math.floor(x + 0.5), y = math.floor(y + 0.5), z = math.floor(z + 0.5),
      r = math.floor(r * 255 + 0.5), g = math.floor(g * 255 + 0.5), b = math.floor(b * 255 + 0.5),
    }
  end
  table.sort(live, function (a, b) return a.y < b.y end)
  local best, bestname = math.huge, nil
  for _, e in ipairs(bucket) do
    local pos, col = 0, 0
    for i = 1, 5 do
      local ev, lv = e.verts[i], live[i]
      pos = pos + math.abs(ev.x - lv.x) + math.abs(ev.y - lv.y) + math.abs(ev.z - lv.z)
      col = col + math.abs(ev.r - lv.r) + math.abs(ev.g - lv.g) + math.abs(ev.b - lv.b)
    end
    local s = pos + 2 * col
    if s < best then best, bestname = s, e.name end
  end
  if best <= 300 then return bestname, best end
  return nil, best
end

-- ---- Puzzle ghosts ---------------------------------------------------------
-- Two attackable NPCs in a puzzle room share ONE mesh (n=1428) and differ only
-- in baked vertex brightness: the DARK one is the vulnerable GOOD_GHOST, the
-- light ones are BAD_GHOSTs, and the game rotates which ghost is vulnerable on
-- a timer. NOT resources -- main.lua detects them ahead of the resource path
-- and returns, so they never queue, never bind a sighting and never reach the
-- parity evidence. The only consumer is the in-world highlight.
--
-- Identity is deliberately POSITION-FREE. These animate, so sampled vertex
-- positions drift with the pose; the two captures we have are byte-identical in
-- position only because both were caught mid-idle. What is stable is the
-- vertexcount plus a SCALE-INVARIANT colour signature -- every sampled vert is
-- neutral (r == g) with a slight blue lift (b = r + ~3). That survives the
-- lighting scale separating the two states (the observed pair differ by a
-- uniform x1.22), which is exactly the thing we must not normalise away: the
-- brightness IS the good/bad tell.
local ghost_ns = {}                      -- vertexcount -> true
local ghost_lum_good, ghost_lum_bad      -- cataloged mean luminances
local function reload_ghosts()
  local raw = SET.load_or_seed("ghosts.txt")
  ghost_ns = {}
  ghost_lum_good, ghost_lum_bad = nil, nil
  if not raw then return end
  for line in raw:gmatch("[^\r\n]+") do
    if not line:match("^%s*#") and not line:match("^%s*$") then
      local name, _tier, rest = line:match("^%s*([%w_]+)|(%d+)|(.+)$")
      if name and rest then
        local n, verts = parse_catalog_verts(rest)
        if n and verts and #verts == 5 then
          ghost_ns[n] = true
          local sum = 0
          for _, v in ipairs(verts) do sum = sum + (v.r + v.g + v.b) / 3 end
          if name == "GOOD_GHOST" then ghost_lum_good = sum / 5
          elseif name == "BAD_GHOST" then ghost_lum_bad = sum / 5 end
        end
      end
    end
  end
end
reload_ghosts()

RES.ghost_n = function (n) return ghost_ns[n] == true end

-- Mean sampled luminance, or nil if this mesh does not carry the ghost colour
-- signature. The caller compares luminance ACROSS the ghosts on screen to pick
-- the vulnerable one; the absolute split below is only the one-ghost fallback.
RES.ghost_lum = function (event, n)
  local step = math.max(1, math.floor(n / 6))
  local sum = 0
  for i = 1, 5 do
    local idx = math.min(n, i * step)
    local ok, r, g, b = pcall(event.vertexcolour, event, idx)
    if not ok then return nil end
    r = math.floor(r * 255 + 0.5)
    g = math.floor(g * 255 + 0.5)
    b = math.floor(b * 255 + 0.5)
    if math.abs(r - g) > 4 or (b - r) < 0 or (b - r) > 8 then return nil end
    sum = sum + (r + g + b) / 3
  end
  return sum / 5
end

-- Midpoint of the two cataloged luminances, or nil if the catalog lacks either.
RES.ghost_split = function ()
  if ghost_lum_good and ghost_lum_bad then
    return (ghost_lum_good + ghost_lum_bad) / 2
  end
  return nil
end

-- ---- Tolerant v1 fallback (sits BELOW v2) ----------------------------------
-- v2 recognises exactly what has a V2 print, and 40 of the catalog's 88 names
-- have none -- they were cataloged as v1 lines, and the self-upgrader can only
-- mint a V2 print from a CONFIDENT v1 classification, which the phase-3 flip
-- removed. Those names went dark: exact-key or nothing, so a single LSB of
-- lighting drift dropped them into the unknown queue with no highlight, and
-- they could never earn the v2 print that would fix them. This tier breaks
-- that deadlock; the names convert to v2 through normal play from here.
--
-- Tightened against the failure that retired the old v1 matcher. That one ran
-- an n+-5 candidate window with cutoff 3000 (see the mis-detection note on
-- learn_resource above). Measured over the current catalog:
--
--   variant vs its own base (T6_ORE/T6_ORE_2)     6-10   harmless, base_name collapses these
--   true re-sight of the same print               4-54   MUST be caught
--   nearest DIFFERENT base name within n+-5       1492   MUST NOT be caught
--
-- so cutoff 3000 sat twice the collision floor and was guaranteed to bind
-- foreign meshes. Exact-n with a 300 cutoff sits 5x under the floor and 5x
-- over the worst true re-sight. Checked against 526 explicitly-ignored
-- non-resource meshes: zero genuine false matches, and 90% of them share no
-- vertex count with any catalog entry at all -- the exact-n gate, not the
-- cutoff, is what does the work here.
local function v1_fallback(key, n)
  -- Below this, meshes carry too little signal to match tolerantly: the only
  -- catalog entry under it is FISHING_SPOT (9 verts, five flat-grey samples)
  -- and 9-vert quads are everywhere in a scene. It has a V2 print, so the
  -- exclusion costs nothing. 1500 is the queue's own admission floor.
  local MIN_N = 1500
  local BIND  = 100   -- <= this: a real match; binds and feeds the upgrader
  local SHOW  = 300   -- <= this: display-only (ambig), never reaches parity
  if n < MIN_N then return nil end
  local bucket = resources_by_n[n]
  if not bucket then return nil end
  -- Scored straight off the fingerprint key -- it already holds the 5 sampled
  -- verts, so this costs no bolt calls. Sorted by y like every other matcher
  -- here, so vertex-order drift cannot swing the result.
  local _, live = parse_catalog_verts(key)
  if not live or #live ~= 5 then return nil end
  table.sort(live, function (a, b) return a.y < b.y end)
  local best, best_score = nil, math.huge
  for _, e in ipairs(bucket) do
    local ev_list = e.verts_sorted
    local pos, col, ok_all = 0, 0, true
    for i = 1, 5 do
      local ev, lv = ev_list[i], live[i]
      if not ev then ok_all = false; break end
      pos = pos + math.abs(ev.x - lv.x) + math.abs(ev.y - lv.y) + math.abs(ev.z - lv.z)
      col = col + math.abs(ev.r - lv.r) + math.abs(ev.g - lv.g) + math.abs(ev.b - lv.b)
    end
    local s = pos + 2 * col
    if ok_all and s < best_score then best, best_score = e, s end
  end
  if not best or best_score > SHOW then return nil end
  return best, best_score, best_score > BIND
end

-- THE classifier (phase 3). Exact v1 fingerprint first (byte-identical key
-- = free and ground truth by construction), then the v2 identity matcher,
-- then the tolerant v1 fallback for names v2 has no print for.
-- Returns (entry, score, ambig) or nil; score is 0 for exact hits and the
-- v2 distance (or the v1 fallback score) otherwise, feeding the Matches tab
-- unchanged.
function RES.classify(event, key, n)
  local exact = resources_catalog[key]
  if exact then
    -- Dinos NEVER bind, even on an exact-pose hit -- force advisory (ambig).
    return exact, 0, (exact.name and exact.name:find("_DINO", 1, true)) ~= nil
  end
  -- DINO detection: vertex-count gate, colour->tier (advisory, never binds).
  if n >= DINO_N - DINO_NW and n <= DINO_N + DINO_NW then
    local tier = dino_tier(event, n)
    if tier then return { name = "T" .. tier .. "_DINO", tier = tier }, 0, true end
    return { name = "DINO", tier = 0 }, 0, true   -- dino, tier not yet referenced
  end
  -- Misses land in v2_reject_memo (both tiers declined); hits land in
  -- v1_fallback_memo. Both are cleared together whenever the catalog changes,
  -- so the split costs nothing and keeps each memo's meaning exact.
  if v2_reject_memo[key] then return nil end
  local fb = v1_fallback_memo[key]
  if fb then return { name = fb.name, tier = fb.tier }, fb.score, fb.ambig end
  local f = v2_cache[key]
  if f == nil then
    f = fingerprint_v2(event, n) or false
    v2_cache[key] = f
  end
  -- A failed v2 sample (f == false) still falls through to the v1 tier: that
  -- one scores off the key, which we already have, so it needs no sampling.
  local hit, bd
  if f then hit, bd = v2_accept(f) end
  if hit then
    return { name = hit.name, tier = hit.tier }, bd, hit.ambig or false
  end
  local e, s, ambig = v1_fallback(key, n)
  if e then
    v1_fallback_memo[key] = { name = e.name, tier = e.tier, score = s, ambig = ambig }
    return { name = e.name, tier = e.tier }, s, ambig
  end
  v2_reject_memo[key] = true
  return nil
end

-- Full-mesh capture for panel previews: local-space verts + client-side MVP,
-- shared by the matched-seen path and the unknown queue (was two verbatim
-- copies inline in the render handler).
-- Full-mesh preview capture is ONLY needed to draw a mesh in the resource
-- panel. It costs up to ~10k bolt calls per unique mesh (5000 verts x 2), so
-- when the panel is closed we skip it entirely -- detection/binding never use
-- pts/mvp, only the preview does. main.lua toggles this with the panel.
local capture_enabled = false
local function capture_mesh(event, n)
  if not capture_enabled then return "", "" end
  local pts = {}
  -- Full capture: the fingerprint gate upstream already rejects n > 5000,
  -- so this cap never truncates -- review marks bank the COMPLETE mesh
  -- (was 3000, which cut the top off 4k-vert marks).
  local pts_n = math.min(n, show_large and 20000 or 5000)
  for vi = 1, pts_n do
    local ok_p, p = pcall(event.vertexpoint, event, vi)
    if not ok_p or not p then break end
    local vx, vy, vz = p:get()
    local ok_c, r, g, b = pcall(event.vertexcolour, event, vi)
    if not ok_c then break end
    pts[#pts + 1] = string.format("%d,%d,%d,%d,%d,%d",
      math.floor(vx + 0.5), math.floor(vy + 0.5), math.floor(vz + 0.5),
      math.floor(r * 255 + 0.5), math.floor(g * 255 + 0.5), math.floor(b * 255 + 0.5))
  end
  local mvp_str = ""
  local ok_vp, vp = pcall(event.viewprojmatrix, event)
  local ok_mm, mm = pcall(event.modelmatrix, event)
  if ok_vp and vp and ok_mm and mm then
    local v = { vp:get() }
    local m = { mm:get() }
    -- Column-major multiplication: OUT = VP * M
    local out = {}
    for col = 0, 3 do
      for row = 0, 3 do
        local sum = 0
        for k = 0, 3 do
          sum = sum + v[k * 4 + row + 1] * m[col * 4 + k + 1]
        end
        out[#out + 1] = tostring(sum)
      end
    end
    mvp_str = table.concat(out, ",")
  end
  return table.concat(pts, ";"), mvp_str
end

-- Matched-mesh record: preview capture (once per fingerprint) + the live
-- Matches-tab entry (keyed by tile so multiple instances all show).
function RES.record_match(event, key, n, name, tier, btx, btz, wx, wz, score, dist2, ambig)
  local seen = resources_matched_seen[key]
  if not seen then
    local pts, mvp_str = capture_mesh(event, n)
    resources_matched_seen[key] = {
      pts = pts, mvp = mvp_str, name = name, tier = tier, n = n,
    }
  elseif capture_enabled and (seen.pts == nil or seen.pts == "") then
    -- Backfill: first matched while the panel was closed (capture off) -> pts
    -- empty. Re-capture now the panel is open so the Matches preview renders.
    seen.pts, seen.mvp = capture_mesh(event, n)
  end
  local mkey = btx .. "," .. btz .. "|" .. name
  current_matches[mkey] = {
    key = key, name = name, tier = tier,
    tx = btx, tz = btz,
    wx = math.floor(wx + 0.5), wz = math.floor(wz + 0.5),
    score = score, dist2 = dist2,
    -- Sticky TTL (frames), refreshed on every re-sight. The Matches list is
    -- rebuilt from current_matches; without a TTL it was wiped every dump tick
    -- (~4/s) and only refilled by scan frames (~5Hz), so any match not caught
    -- in a given dump window blinked out -- the panel flicker. Aged in
    -- tick_resources; entries survive gaps between sightings.
    ttl = RES_LEARNED_TTL,
  }
  v2_observe(event, key, n, name, tier, score, ambig, btx, btz)
end

-- Unknown-mesh queue admission (low-poly filtered; sticky until TTL).
function RES.queue_unknown(event, key, n, wx, wy, wz, dist2)
  if resources_ignored[key] then return end
  -- Vertexcount window from the panel's verts slider (default 1500..5000).
  -- Below the min is usually decals/sparkles/projectiles; the panel can lower it
  -- to surface small puzzle props. Cataloged low-poly resources (FISHING_SPOT
  -- n=9) classify in the handler before this runs.
  if n < queue_vmin then return end
  if not show_large and n > queue_vmax then return end   -- upper bound off under SHOW LARGE
  local tx = math.floor(wx / RES_TILE_UNITS)
  local tz = math.floor(wz / RES_TILE_UNITS)
  -- v1 drew a blank on this mesh: a confident v2 hit here is exactly the
  -- coverage gain the overhaul is after -- logged as V1-MISS in the shadow.
  v2_observe(event, key, n, nil, nil, nil, nil, tx, tz)
  local entry = resources_learned[key]
  if not entry then
    local pts, mvp_str = capture_mesh(event, n)
    resources_learned[key] = {
      key = key, n = n,
      wx = math.floor(wx + 0.5),
      wy = math.floor(wy + 0.5),
      wz = math.floor(wz + 0.5),
      tx = tx, tz = tz,
      dist2 = dist2, ttl = RES_LEARNED_TTL,
      pts = pts, mvp = mvp_str,
    }
  else
    entry.dist2 = dist2
    entry.wx = math.floor(wx + 0.5)
    entry.wy = math.floor(wy + 0.5)
    entry.wz = math.floor(wz + 0.5)
    entry.tx = tx; entry.tz = tz
    entry.ttl = RES_LEARNED_TTL
    -- Backfill the preview: an entry first queued while the panel was CLOSED
    -- has empty pts/mvp (capture was gated off for perf). Once the panel opens
    -- capture_enabled flips true, so re-capture on the next sighting -- else a
    -- resource walked past before opening the panel previews blank forever.
    -- capture_mesh returns "" while disabled, so this stays a no-op then.
    if capture_enabled and (entry.pts == nil or entry.pts == "") then
      entry.pts, entry.mvp = capture_mesh(event, n)
    end
  end
end

