-- Parse a resource icon name into (type, tier). Convention: t<N>_<type>.
local function resource_verdict(name)
  -- Catalog uses UPPERCASE (T10_ORE) plus variant suffixes (T4_TREE_2).
  -- Lowercase, then match "t<N>_<letters>" so variants collapse to their
  -- base type and non-tier names (FISHING_SPOT, LARGE_CHEST) don't match.
  local n = name:lower()
  local tier, rtype = n:match("^t(%d+)_(%a+)")
  if not tier then return nil end
  tier = tonumber(tier)
  local max = resource_type_max[rtype]
  if not max then return nil end
  if tier < max - 1 then return "bonus" end
  return nil                     -- top two tiers: no inference
end

-- Bind a resource model to the room it stands in. Sightings are STICKY (only a
-- floor wipe clears them), so a bad binding is permanent and silently poisons
-- parity forever after -- hence the guards below reject rather than guess.
--
-- Sticky is CORRECT and deliberate: "this room contains a T6 ore" is a permanent
-- truth about the floor, and the model stops rendering the moment you walk away,
-- so a non-sticky store would forget every room you left. The sightings are not
-- a view of what is on screen; they are the floor's evidence log.
--
-- A sighting is only admissible if the model's coordinates land in a cell that
-- both EXISTS and is OPENED:
--   * No cell -> the derived coords are nonsense. Seen live: FISHING_SPOT bound
--     to "2,-1", which is off the top of the map entirely.
--   * Unopened cell -> impossible. You cannot see a resource through a closed
--     door, so any sighting attributed to a room you have never entered is by
--     definition a mis-binding, not evidence. Admitting one marks a room bonus
--     off a resource that isn't in it.
-- Those two catch a GROSS mis-bind, but not the dangerous one: a cell that is
-- real and opened but simply not the right one sails straight through.
--
-- COORDINATES: world_room_to_grid is the MIRROR model (gz reflects world z),
-- fixed in 2bbe5f4 and pinned by spec.py's axis tests. A stale comment here
-- used to describe the pre-fix shift model as "known broken" -- deleted
-- 2026-07-18 after verifying the shipped function is the tested mirror.
-- Cell-level half of resource binding, shared by the local detector and the
-- party-sync merge: the guards below (opened body, base invariant) must hold
-- for REMOTE sightings too -- a peer's mis-detection is as poisonous as ours.
-- `remote` suppresses re-emission so merged events can't ping-pong.
local bind_resource_cell
local function bind_resource_sighting(res_tx, res_tz, name)
  local gx, gz = world_room_to_grid(math.floor(res_tx / 16), math.floor(res_tz / 16))
  if not gx then return end
  bind_resource_cell(gx .. "," .. gz, name, false)
end
bind_resource_cell = function (ck, name, remote)
  local cell = cell_at(ck)
  if not cell then return end
  -- Opened-ness is decided by the room BODY. Key doors and skill doors need no
  -- special case: they are OVERLAYS (silver_shield, DOOR_FARMING) drawn on top
  -- of an UNOPENED_* body, so the body still reads as unopened.
  local body
  for _, n in ipairs(cell.images) do
    if is_room_body(n) then body = n; break end
  end
  if not body then
    -- Every room on the map has a body signature, so a classified cell with no
    -- body is a detection failure -- critical, and never expected. Report it
    -- instead of quietly treating it as "not opened", which would bury the real
    -- fault under a silent skip.
    SET.dev_save("resource_diag.txt",
      ("CRITICAL: cell %s has no room-body signature; images=%s\n")
      :format(ck, table.concat(cell.images, ",")))
    return
  end
  if body:sub(1, 9) == "UNOPENED_" then return end
  -- BASE NEVER HOLDS A SKILLING RESOURCE. User-confirmed invariant, not a
  -- heuristic -- the generator does not put them there. So a sighting that binds
  -- to base is a mis-DETECTION by definition, whatever the coordinates say, and
  -- admitting one is guaranteed to be wrong.
  --
  -- This is not hypothetical: it killed a floor on 2026-07-14. A ~1820-vert mesh
  -- in base (the smuggler, most likely) matched BOTH T1_TREE_4 (1815 verts) and
  -- T1_TREE_2 (1824) -- the n+-5 bucket window reaches both from 1820 -- so base
  -- was inferred bonus off a tree that does not exist, contradicting base being
  -- crit by definition.
  --
  -- CONTAINS, DOES NOT CURE. The same loose match (n+-5, cutoff 3000, versus the
  -- ground-key matcher's exact-n and 300) will mis-label meshes in ANY room; base
  -- is only the one room where we have an invariant to catch it with. Elsewhere a
  -- false T1 silently marks a real room bonus and cascades. See dg-open-bugs.
  if body == "ICON_BASE" then
    SET.dev_save("resource_diag.txt",
      ("REJECTED %s bound to base %s -- base never holds skilling resources, so\n" ..
       "this is a mis-detection. The matcher (n+-5 / cutoff 3000) is too loose.\n")
      :format(name, ck))
    return
  end
  local bag = S.resource_sightings[ck]
  if not bag then bag = {}; S.resource_sightings[ck] = bag end
  if not bag[name] then
    bag[name] = true
    if not remote and SET.sync.emit then
      SET.sync.emit({ t = "resource", c = ck, r = name })
    end
  end
end

-- ============================================================================
-- FINGERPRINT V2 (overhaul phase 2) -- permutation-invariant features.
--
-- The v1 identity (5 verts at fixed indices) breaks whenever a mesh's vertex
-- order shifts (LOD variants, section reordering in composite models) and its
-- thin sample cross-matched foreign meshes (the base smuggler wore two tree
-- labels at once). V2 characterises the mesh by AGGREGATES of a 24-vert
-- spread -- vertex count, bbox extents, mean colour, an 8-bin colour
-- histogram, a 4-bin vertical profile and mean horizontal radius -- which
-- survive reordering (a fair sample's distribution is order-free) and, for
-- the colour features, survive animation pose too (matters for dinos later).
--
-- SHADOW MODE this phase: v2 matches are computed and logged against v1's
-- verdicts (v2_shadow.txt, dev) but do NOT feed binds; the self-upgrader
-- grows the catalog from confident v1 classifications so the v2 side fills
-- through normal play. The matcher flip is phase 3, thresholds set from the
-- shadow data. Cataloging effort is explicitly cheap per the user; multiple
-- v2 fingerprints per name are the DESIGN, not a compromise.
-- ============================================================================
local V2_K = 24              -- sampled verts per fingerprint
local V2_MAX_PER_NAME = 12   -- self-upgrade cap per resource name
local V2_DEDUPE_DIST = 50    -- closer than this to an existing entry = same pose/variant
local v2_entries = {}        -- flat list: { name, tier, n, ext, mrgb, chist, vq, rad }
local v2_count_by_name = {}
local v2_cache = {}          -- v1 fingerprint key -> v2 features (per floor)
local v2_shadow_seen = {}    -- dedupe shadow-log lines per (tile|v1name)
local v2_shadow_log = ""

local function fingerprint_v2(event, n)
  local xs, ys, zs = {}, {}, {}
  local rs, gs, bs = {}, {}, {}
  for i = 1, V2_K do
    local idx = math.max(1, math.min(n, math.floor(i * n / (V2_K + 1))))
    local ok_p, p = pcall(event.vertexpoint, event, idx)
    if not ok_p or not p then return nil end
    local x, y, z = p:get()
    local ok_c, r, g, b = pcall(event.vertexcolour, event, idx)
    if not ok_c then return nil end
    xs[i], ys[i], zs[i] = x, y, z
    rs[i] = math.floor(r * 255 + 0.5)
    gs[i] = math.floor(g * 255 + 0.5)
    bs[i] = math.floor(b * 255 + 0.5)
  end
  local minx, maxx = math.huge, -math.huge
  local miny, maxy = math.huge, -math.huge
  local minz, maxz = math.huge, -math.huge
  local cx, cz = 0, 0
  local mr, mg, mb = 0, 0, 0
  local chist = { 0, 0, 0, 0, 0, 0, 0, 0 }
  for i = 1, V2_K do
    local x, y, z = xs[i], ys[i], zs[i]
    if x < minx then minx = x end
    if x > maxx then maxx = x end
    if y < miny then miny = y end
    if y > maxy then maxy = y end
    if z < minz then minz = z end
    if z > maxz then maxz = z end
    cx = cx + x; cz = cz + z
    mr = mr + rs[i]; mg = mg + gs[i]; mb = mb + bs[i]
    local bin = (rs[i] >= 128 and 4 or 0) + (gs[i] >= 128 and 2 or 0)
              + (bs[i] >= 128 and 1 or 0) + 1
    chist[bin] = chist[bin] + 1
  end
  cx, cz = cx / V2_K, cz / V2_K
  local vq = { 0, 0, 0, 0 }
  local dy = maxy - miny
  if dy < 1 then dy = 1 end
  local rad = 0
  for i = 1, V2_K do
    local q = math.min(4, 1 + math.floor((ys[i] - miny) / dy * 4))
    vq[q] = vq[q] + 1
    local dx, dz2 = xs[i] - cx, zs[i] - cz
    rad = rad + math.sqrt(dx * dx + dz2 * dz2)
  end
  return {
    n = n,
    ext = { maxx - minx, maxy - miny, maxz - minz },
    mrgb = { mr / V2_K, mg / V2_K, mb / V2_K },
    chist = chist, vq = vq, rad = rad / V2_K,
  }
end

-- Weighted L1 feature distance. Initial weights are order-of-magnitude
-- guesses; phase 3 sets them from v2_shadow.txt data the same way the v1
-- two-band cutoffs came from match_log data.
local function v2_dist(a, b)
  local d = 0
  local nmax = math.max(a.n, b.n)
  d = d + math.abs(a.n - b.n) / nmax * 400
  for i = 1, 3 do d = d + math.abs(a.ext[i] - b.ext[i]) / 8 end
  for i = 1, 3 do d = d + math.abs(a.mrgb[i] - b.mrgb[i]) * 1.5 end
  for i = 1, 8 do d = d + math.abs(a.chist[i] - b.chist[i]) * 8 end
  for i = 1, 4 do d = d + math.abs(a.vq[i] - b.vq[i]) * 6 end
  d = d + math.abs(a.rad - b.rad) / 4
  return d
end

-- Variant suffixes collapse for rivalry: T3_TREE vs T3_TREE_2 is the same
-- resource for every consumer (verdict works on the base), so confusion
-- between them is harmless and must not create ambiguity.
local function base_name(nm)
  return (nm:gsub("_%d+$", ""))
end

-- Best entry + best rival with a DIFFERENT BASE NAME across the whole v2
-- catalog (no n-bucket prefilter: the n term of the distance does that job
-- softly, which is the point -- LOD drift must not hide candidates).
local function v2_match(f)
  local best, best_d, rival, rival_d = nil, math.huge, nil, math.huge
  for _, e in ipairs(v2_entries) do
    local d = v2_dist(f, e)
    if d < best_d then
      if best and base_name(best.name) ~= base_name(e.name) then
        rival, rival_d = best, best_d
      end
      best, best_d = e, d
    elseif best and base_name(e.name) ~= base_name(best.name) and d < rival_d then
      rival, rival_d = e, d
    end
  end
  return best, best_d, rival, rival_d
end

-- IDENTITY ACCEPTANCE (phase 3, thresholds from the 2026-07-19 distance
-- matrix): a live re-sight of a cataloged mesh lands at d=0-2; the nearest
-- print of a DIFFERENT base name observed anywhere was 78; same-family
-- variants overlap cross-tier distances (41-346 vs 78-220), so v2 does NOT
-- generalise across variants -- it recognises exactly what is cataloged,
-- and every variant earns its own print (self-upgrade or one manual
-- naming). Accept = tight distance AND a clear gap to any other-base print;
-- a rival inside the floor demotes the match to display-only (never binds).
local V2_ACCEPT      = 30
local V2_RIVAL_FLOOR = 60

-- Pure decision half, exposed for spec.py: features in, verdict out.
local function v2_accept(f)
  local best, bd, rival, rd = v2_match(f)
  if not best or bd > V2_ACCEPT then return nil, bd end
  if rival and rd < V2_RIVAL_FLOOR then
    return { name = best.name, tier = best.tier, ambig = true }, bd
  end
  return { name = best.name, tier = best.tier }, bd
end

-- Rejection memo: features are a pure function of the v1 fingerprint key,
-- so a key that failed acceptance fails until the catalog changes (reload
-- or a self-upgrade append) -- cleared at both of those sites.
local v2_reject_memo = {}
-- Same deal for the tolerant v1 fallback tier (defined next to the classifier,
-- declared here so the reload/self-upgrade sites below can clear it). Holds
-- { name, tier, score, ambig } | false -- false meaning "scored, no hit".
local v1_fallback_memo = {}

local function v2_serialize(name, tier, f)
  local q = function (x) return math.floor(x + 0.5) end
  return string.format("V2|%s|%d|%d|%d,%d,%d|%d,%d,%d|%s|%s|%d",
    name, tier or 0, f.n,
    q(f.ext[1]), q(f.ext[2]), q(f.ext[3]),
    q(f.mrgb[1]), q(f.mrgb[2]), q(f.mrgb[3]),
    table.concat(f.chist, ","),
    table.concat(f.vq, ","),
    q(f.rad))
end

local function v2_parse(line)
  local name, tier, n, ext_s, mrgb_s, chist_s, vq_s, rad_s = line:match(
    "^V2|([%w_]+)|(%d+)|(%d+)|([%-%d,]+)|([%d,]+)|([%d,]+)|([%d,]+)|(%d+)$")
  if not name then return nil end
  local function nums(s)
    local out = {}
    for v in s:gmatch("[^,]+") do out[#out + 1] = tonumber(v) end
    return out
  end
  local ext, mrgb, chist, vq = nums(ext_s), nums(mrgb_s), nums(chist_s), nums(vq_s)
  if #ext ~= 3 or #mrgb ~= 3 or #chist ~= 8 or #vq ~= 4 then return nil end
  return { name = name, tier = tonumber(tier), n = tonumber(n),
           ext = ext, mrgb = mrgb, chist = chist, vq = vq, rad = tonumber(rad_s) }
end

-- SELF-UPGRADING CATALOG: a confident, unambiguous v1 classification
-- appends its v2 fingerprint under the same name -- the v2 side fills in
-- through normal play, and the 82 existing v1 entries never need manual
-- re-cataloging. Deduped by distance so a parked player doesn't append the
-- same pose 60x/second; capped per name as a runaway guard.
local function v2_self_upgrade(name, tier, f)
  -- DINOS ARE EXCLUDED until the dino phase: one shared mesh across tiers,
  -- tier carried ONLY by colour, positions vary with animation pose
  -- (confirmed 2026-07-19: T9/T4 review captures, identical n=3012 and
  -- sample indices, different colours). The current v2 features cannot be
  -- trusted to separate tiers there; v1 exact-pose prints stay safe because
  -- a byte-identical key cannot be the wrong dino.
  if name:find("_DINO", 1, true) then return end
  if (v2_count_by_name[name] or 0) >= V2_MAX_PER_NAME then return end
  for _, e in ipairs(v2_entries) do
    if e.name == name and v2_dist(f, e) < V2_DEDUPE_DIST then return end
  end
  local entry = { name = name, tier = tier or 0, n = f.n,
                  ext = f.ext, mrgb = f.mrgb, chist = f.chist,
                  vq = f.vq, rad = f.rad }
  v2_entries[#v2_entries + 1] = entry
  v2_count_by_name[name] = (v2_count_by_name[name] or 0) + 1
  -- Only the REJECT memo is cleared: a new print may rescue a mesh that matched
  -- nothing. Meshes that already have a v1-fallback verdict keep it -- a new
  -- print of the same name would only re-derive the same name, and wiping that
  -- memo too made every append re-classify every mesh in view, which is O(M^2)
  -- on walking into a room full of previously-dark resources.
  v2_reject_memo = {}
  -- last_res_raw is kept exactly in sync (below, and by reload_resources), so
  -- use it instead of re-reading a ~30KB file on every append.
  local raw = last_res_raw or SET.load_or_seed("resources.txt") or ""
  if #raw > 0 and not raw:match("\n$") then raw = raw .. "\n" end
  raw = raw .. v2_serialize(name, tier, f) .. "\n"
  bolt.saveconfig("resources.txt", raw)
  last_res_raw = raw   -- in-memory state already updated; skip the reparse
end

-- Shadow observation: compute v2 for this mesh (memoised on the v1 key --
-- static objects cost one sample, not 60/s), maybe self-upgrade, and log
-- v1-vs-v2 agreement. v1name == nil means v1 drew a blank (the queue path):
-- a confident v2 hit there is exactly the coverage the overhaul is after.
local function v2_observe(event, key, n, v1name, v1tier, v1score, v1ambig, tx, tz)
  local f = v2_cache[key]
  if f == nil then
    f = fingerprint_v2(event, n) or false
    v2_cache[key] = f
  end
  if not f then return end
  if v1name and not v1ambig and v1score and v1score <= 100 then
    v2_self_upgrade(v1name, v1tier, f)
  end
  if not SET.DEV then return end
  local sk = tx .. "," .. tz .. "|" .. tostring(v1name)
  if v2_shadow_seen[sk] then return end
  v2_shadow_seen[sk] = true
  local best, bd, rival, rd = v2_match(f)
  -- Provisional accept band for LOG CLASSIFICATION only (first floor's data:
  -- same-object re-match = 0, foreign meshes vs an ore print = 713+; the
  -- phase-3 threshold will be set from accumulated data, this just keeps the
  -- log readable). Nearest-neighbor without a band mislabeled every unknown
  -- as the closest of a 3-entry catalog.
  local V2_LOG_BAND = 300
  local agree
  if not best then agree = "V2-EMPTY"
  elseif not v1name then
    -- Only an in-band hit is a coverage candidate; far misses are noise and
    -- movers walking across tiles would flood the log with them.
    if bd > V2_LOG_BAND then return end
    agree = "V1-MISS"
  elseif best.name == v1name then agree = "AGREE"
  else agree = "DISAGREE" end
  v2_shadow_log = (v2_shadow_log .. string.format(
    "%-9s tile=%d,%-4d n=%-5d v1=%-16s s=%-6s v2=%-16s d=%-6d rival=%s\n",
    agree, tx, tz, n, tostring(v1name), tostring(v1score),
    best and best.name or "(none)", best and math.floor(bd + 0.5) or -1,
    rival and string.format("%s:%d", rival.name, math.floor(rd + 0.5)) or "(none)"))
    :sub(-12000)
  SET.dev_save("v2_shadow.txt", v2_shadow_log)
end

local RES_LEARNED_TTL   = 300           -- frames before an unseen entry expires
-- Unknown-queue vertexcount bounds, driven by the panel's verts slider. Default
-- min 1500 (decals/sparkles below that are noise); max 5000 = fingerprint cap.
local queue_vmin, queue_vmax = 1500, 5000
-- SHOW LARGE (panel toggle): lifts the fingerprint's >5000-vert reject, the
-- >4-tile bbox reject, and the queue's upper bound, so big/spread meshes (large
-- puzzle apparatus, scenery) can be surfaced. Noisy -- meant to be toggled on
-- only while hunting a specific large model.
local show_large = false

local resources_catalog = {}   -- fingerprint_key -> { name, tier }
local resources_ignored = {}   -- fingerprint_key -> true
-- resources_learned and last_ign_res_raw are forward-declared at the top of
-- the file so the resource browser's onmessage handler can close over them.
local function fingerprint_resource(event)
  local n = event:vertexcount()
  if n < 4 then return nil end
  if not show_large and n > 5000 then return nil end   -- lifted by SHOW LARGE
  local step = math.max(1, math.floor(n / 6))
  local parts = { tostring(n) }
  -- Local-space bbox from the 5 samples; used to reject anything that spans
  -- more than one game tile in X or Z.
  local x_min, x_max = math.huge, -math.huge
  local z_min, z_max = math.huge, -math.huge
  for i = 1, 5 do
    local idx = math.min(n, i * step)
    local ok_p, p = pcall(event.vertexpoint, event, idx)
    if not ok_p or not p then return nil end
    local x, y, z = p:get()
    local ok_c, r, g, b = pcall(event.vertexcolour, event, idx)
    if not ok_c then return nil end
    if x < x_min then x_min = x end
    if x > x_max then x_max = x end
    if z < z_min then z_min = z end
    if z > z_max then z_max = z end
    parts[#parts + 1] = string.format("%d,%d,%d,%d,%d,%d,%d", idx,
      math.floor(x + 0.5), math.floor(y + 0.5), math.floor(z + 0.5),
      math.floor(r * 255 + 0.5), math.floor(g * 255 + 0.5), math.floor(b * 255 + 0.5))
  end
  -- Relaxed from 1 tile to 4 tiles so large multi-part meshes (dinos, etc.)
  -- can still enter the queue. Very-wide scenery still gets rejected -- unless
  -- SHOW LARGE is on, which lifts this bbox reject too.
  if not show_large
     and ((x_max - x_min) > RES_TILE_UNITS * 4 or (z_max - z_min) > RES_TILE_UNITS * 4) then
    return nil
  end
  return table.concat(parts, "|"), n
end

-- Parsed catalog entry: keeps the 5 sample verts as numbers so we can do
-- tolerant matching (positions may drift a few units, vertex colours may
-- get lighting-tinted). Index by vertex count for cheap candidate lookup.
local resources_by_n = {}   -- n -> list of parsed catalog entries

local function parse_catalog_verts(rest)
  local n_str, tail = rest:match("^(%d+)|(.+)$")
  local n = tonumber(n_str)
  if not n then return nil end
  local verts = {}
  for chunk in tail:gmatch("[^|]+") do
    local ix, x, y, z, r, g, b = chunk:match(
      "^(%-?%d+),(%-?%d+),(%-?%d+),(%-?%d+),(%-?%d+),(%-?%d+),(%-?%d+)$")
    if ix then
      verts[#verts + 1] = {
        idx = tonumber(ix),
        x = tonumber(x), y = tonumber(y), z = tonumber(z),
        r = tonumber(r), g = tonumber(g), b = tonumber(b),
      }
    end
  end
  return n, verts
end

local function reload_resources()
  local raw = SET.load_or_seed("resources.txt")
  if raw == last_res_raw then return end
  last_res_raw = raw
  resources_catalog = {}
  resources_by_n = {}
  v2_entries = {}
  v2_count_by_name = {}
  v2_reject_memo = {}     -- catalog changed: rejected meshes get a fresh chance
  v1_fallback_memo = {}
  if raw then
    for line in raw:gmatch("[^\r\n]+") do
      if not line:match("^%s*#") and not line:match("^%s*$") then
        local v2e = v2_parse(line)
        if v2e then
          v2_entries[#v2_entries + 1] = v2e
          v2_count_by_name[v2e.name] = (v2_count_by_name[v2e.name] or 0) + 1
        else
        local name, tier, rest = line:match("^%s*([%w_]+)|(%d+)|(.+)$")
        if name and tier and rest then
          local n, verts = parse_catalog_verts(rest)
          if n and verts then
            -- Pre-sort verts by y for the order-invariant scorer path. Sorting
            -- once at load beats sorting every candidate every frame.
            local verts_sorted = { verts[1], verts[2], verts[3], verts[4], verts[5] }
            table.sort(verts_sorted, function (a, b) return a.y < b.y end)
            local entry = { name = name, tier = tonumber(tier), n = n,
                            verts = verts, verts_sorted = verts_sorted }
            resources_by_n[n] = resources_by_n[n] or {}
            resources_by_n[n][#resources_by_n[n] + 1] = entry
            -- Keep the exact-key map as a fast-path when the fingerprint is byte-identical.
            resources_catalog[rest] = { name = name, tier = tonumber(tier) }
          end
        end
        end
      end
    end
  end
end

local function reload_ignored_resources()
